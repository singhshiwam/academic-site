// Regenerates assets/js/world-data.js. Run from a folder where these are installed:
//   npm i world-atlas topojson-client d3-geo   then   node /path/to/tools/make_map.mjs
// (Paths to node_modules are relative to the folder you run it from.)
import fs from 'fs';
import { feature } from 'topojson-client';
import { geoNaturalEarth1, geoPath, geoGraticule10 } from 'd3-geo';
const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-110m.json'));
const land = feature(topo, topo.objects.land);
// drop Antarctica-ish polygons south of -58
land.features[0].geometry.coordinates = land.features[0].geometry.coordinates.filter(p => Math.max(...p[0].map(c => c[1])) > -58);
const W = 1000, H = 470;
const proj = geoNaturalEarth1().rotate([-30, 0]).fitExtent([[6, 6], [W - 6, H - 6]], land);
const path = geoPath(proj);
const r = n => Math.round(n * 10) / 10;
let d = path(land).replace(/(\d+\.\d+)/g, m => String(r(+m)));
const grat = path(geoGraticule10()).replace(/(\d+\.\d+)/g, m => String(r(+m)));
const places = [
  { id: 'roorkee', name: 'Roorkee', lon: 77.89, lat: 29.87, home: true, what: 'IIT Roorkee, home institute' },
  { id: 'sapporo', name: 'Sapporo', lon: 141.35, lat: 43.06, what: 'GEWEX Open Science Conference, July 2024', kind: 'talk' },
  { id: 'chiba', name: 'Chiba', lon: 140.04, lat: 35.65, what: 'JpGU Meeting, May 2025', kind: 'talk' },
  { id: 'washington', name: 'Washington, D.C.', lon: -77.04, lat: 38.91, what: 'AGU Fall Meeting, December 2024', kind: 'talk' },
  { id: 'singapore', name: 'Singapore', lon: 103.82, lat: 1.35, what: 'AOGS Annual Meeting, July 2025', kind: 'talk' },
  { id: 'pune', name: 'Pune', lon: 73.86, lat: 18.52, what: 'INTROMET-2025, IITM, November 2025', kind: 'talk' },
  { id: 'vienna', name: 'Vienna', lon: 16.37, lat: 48.21, what: 'EGU General Assembly, May 2026', kind: 'talk' },
  { id: 'lauenburg', name: 'Lauenburg', lon: 10.56, lat: 53.37, what: 'HPC4Climate Summer School, July 2025', kind: 'school' },
  { id: 'bengaluru', name: 'Bengaluru', lon: 77.59, lat: 12.97, what: 'ICTS data assimilation school, May 2024', kind: 'school' },
  { id: 'hyderabad', name: 'Hyderabad', lon: 78.49, lat: 17.39, what: 'NRSC data assimilation training, January 2025', kind: 'school' },
].map(p => { const [x, y] = proj([p.lon, p.lat]); return { ...p, x: r(x), y: r(y) }; });
// great-circle arcs from Roorkee, as projected polylines
import { geoInterpolate } from 'd3-geo';
const home = places[0];
for (const p of places.slice(1)) {
  const f = geoInterpolate([home.lon, home.lat], [p.lon, p.lat]);
  const pts = []; for (let i = 0; i <= 48; i++) { const [x, y] = proj(f(i / 48)); pts.push(`${r(x)} ${r(y)}`); }
  p.arc = 'M' + pts.join('L');
}
fs.writeFileSync(new URL('../assets/js/world-data.js', import.meta.url),
  '/* Generated by tools/make_map.mjs from Natural Earth 1:110m land (world-atlas), Natural Earth projection. */\n' +
  'window.WORLD=' + JSON.stringify({ w: W, h: H, land: d, grat, places }) + ';\n');
console.log('land path chars', d.length, 'grat', grat.length);
